const minutesAgo = (minutes: number) => new Date(Date.now() - minutes * 60_000).toISOString()
const hoursAgo = (hours: number) => minutesAgo(hours * 60)
const daysAgo = (days: number) => hoursAgo(days * 24)

function message(
  conversationId: string,
  id: string,
  role: Message['role'],
  authorName: string,
  body: string,
  minutes: number,
  extra: Partial<Message> = {},
): Message {
  return {
    id,
    conversationId,
    role,
    authorId: role === 'agent' ? 'me' : `p-${authorName.toLowerCase().replace(/\s+/g, '-')}`,
    authorName,
    body,
    createdAt: minutesAgo(minutes),
    status: role === 'agent' ? 'read' : 'delivered',
    kind: 'text',
    ...extra,
  }
}

